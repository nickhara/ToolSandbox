<#
.SYNOPSIS
    Repairs DFS folder targets that were incorrectly removed by
    Remove-InactiveDfsTargetsV2.ps1, using parallel processing for speed.

.DESCRIPTION
    Reads a removals CSV produced by Remove-InactiveDfsTargetsV2.ps1 and
    attempts to restore targets whose UNC path is actually accessible.

    For each row where Status is "Removed":
      1. Checks if the TargetPath is reachable (Test-Path with timeout).
      2. If reachable, checks whether the DFS folder link still exists.
         - If the link exists, re-adds the target via New-DfsnFolderTarget.
         - If the link is gone (auto-deleted when the last target was removed),
           recreates it via New-DfsnFolder with the target path.

    All targets are processed in parallel using ForEach-Object -Parallel
    (PowerShell 7+). The -ThrottleLimit parameter controls concurrency.

    Supports -WhatIf to preview all restorations without making changes.

.PARAMETER RemovalsCsvPath
    Path to the removals CSV file generated by Remove-InactiveDfsTargetsV2.ps1.
    Expected columns: Timestamp, DfsServer, LinkPath, TargetPath, Reason, Status.

.PARAMETER ReachabilityTimeoutSeconds
    Timeout in seconds for UNC path reachability checks. Defaults to 15.

.PARAMETER ProgressFile
    Path to a JSON file used to track which rows have been processed. On restart,
    rows already recorded in this file are skipped, allowing the script to resume
    where it left off. When omitted, a default file named
    repair_progress_<csv-basename>.json is created next to this script.

.PARAMETER ResetProgress
    When set, deletes the progress file before starting, forcing a full re-scan.

.PARAMETER LogFilePath
    Optional transcript log path. When omitted, a timestamped log file is
    created under a logs\ folder next to this script.

.PARAMETER ThrottleLimit
    Maximum number of concurrent parallel operations. Defaults to 16.
    Higher values increase parallelism but also increase load on the DFS
    servers and the network.

.EXAMPLE
    .\Repair-DfsTargetsFromCsv.ps1 -RemovalsCsvPath ".\logs\removals_20260328_100107.csv" -WhatIf

.EXAMPLE
    .\Repair-DfsTargetsFromCsv.ps1 -RemovalsCsvPath ".\logs\removals_20260328_100107.csv"

.EXAMPLE
    .\Repair-DfsTargetsFromCsv.ps1 -RemovalsCsvPath ".\logs\removals_20260328_100107.csv" -ThrottleLimit 32

.NOTES
    Requires PowerShell 7 or later (ForEach-Object -Parallel).
    Requires the DFSN PowerShell module (New-DfsnFolder, New-DfsnFolderTarget)
    and appropriate permissions to modify the DFS namespace.
#>

[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory=$true, HelpMessage="Path to the removals CSV generated by Remove-InactiveDfsTargetsV2.ps1.")]
    [string] $RemovalsCsvPath,

    [Parameter(Mandatory=$false, HelpMessage="Timeout in seconds for UNC path reachability checks.")]
    [int] $ReachabilityTimeoutSeconds = 15,

    [Parameter(Mandatory=$false, HelpMessage="JSON progress file for resumable runs. Rows recorded here are skipped on restart.")]
    [string] $ProgressFile,

    [Parameter(Mandatory=$false, HelpMessage="Delete the progress file before starting, forcing a full re-scan.")]
    [switch] $ResetProgress,

    [Parameter(Mandatory=$false, HelpMessage="Optional transcript log path.")]
    [string] $LogFilePath,

    [Parameter(Mandatory=$false, HelpMessage="Max concurrent operations for parallel processing. Default is 16.")]
    [int] $ThrottleLimit = 16
)

$ErrorActionPreference = "Stop"

# ─────────────────────────────────────────────────────────────────────────────
# PowerShell 7+ guard (required for ForEach-Object -Parallel)
# ─────────────────────────────────────────────────────────────────────────────

if ($PSVersionTable.PSVersion.Major -lt 7) {
    Write-Error "This script requires PowerShell 7 or later for parallel processing (ForEach-Object -Parallel). Current version: $($PSVersionTable.PSVersion)"
    return
}

# ─────────────────────────────────────────────────────────────────────────────
# Logging setup
# ─────────────────────────────────────────────────────────────────────────────

if ([string]::IsNullOrWhiteSpace($LogFilePath)) {
    $timestamp = Get-Date -Format "yyyyMMdd_HHmmss"
    $LogFilePath = Join-Path $PSScriptRoot "logs\Repair-DfsTargetsFromCsv_$timestamp.log"
}

$logDirectory = Split-Path -Path $LogFilePath -Parent
if (-not [string]::IsNullOrWhiteSpace($logDirectory) -and -not (Test-Path $logDirectory)) {
    New-Item -ItemType Directory -Path $logDirectory -Force -WhatIf:$false | Out-Null
}

$TranscriptStarted = $false
Start-Transcript -Path $LogFilePath -Append -WhatIf:$false | Out-Null
$TranscriptStarted = $true
Write-Host "Transcript log: $LogFilePath" -ForegroundColor Gray

function Write-Status {
    param([string]$Message)
    $ts = (Get-Date).ToString("HH:mm:ss.fff")
    Write-Host "[$ts] $Message" -ForegroundColor Gray
}

# ─────────────────────────────────────────────────────────────────────────────
# Thread-safe counters and collections for parallel processing
# ─────────────────────────────────────────────────────────────────────────────

$totalCsvRows          = 0
$totalRemoved          = 0
$totalSkipped          = 0

# Synchronized hashtable for thread-safe counter updates inside parallel blocks
$sharedCounters = [hashtable]::Synchronized(@{
    Reachable      = [int]0
    Unreachable    = [int]0
    Restored       = [int]0
    LinksRecreated = [int]0
    TargetsReadded = [int]0
    Errors         = [int]0
    Processed      = [int]0
})

# Thread-safe dictionaries for outcomes and progress tracking
$repairOutcomes = [System.Collections.Concurrent.ConcurrentDictionary[string,string]]::new()
$newCompletedRows = [System.Collections.Concurrent.ConcurrentDictionary[string,string]]::new()

# Thread-safe bag for recovery report records
$recoveryRecords = [System.Collections.Concurrent.ConcurrentBag[PSObject]]::new()

# Recovery report CSV
$recoveryReportPath = Join-Path $PSScriptRoot ("results\recovery_all_" + (Get-Date -Format "yyyyMMdd_HHmmss") + ".csv")
Write-Host "Recovery report will be written to: $recoveryReportPath" -ForegroundColor Gray

# ─────────────────────────────────────────────────────────────────────────────
# Helper: Test UNC path reachability with timeout (runspace-based)
# ─────────────────────────────────────────────────────────────────────────────

function Test-TargetReachable {
    param(
        [Parameter(Mandatory=$true)]
        [string] $TargetPath,
        [int] $TimeoutSeconds = 10
    )

    $ps = $null
    try {
        $ps = [PowerShell]::Create()
        $ps.AddCommand("Test-Path").AddParameter("Path", $TargetPath) | Out-Null
        $handle = $ps.BeginInvoke()

        if ($handle.AsyncWaitHandle.WaitOne([TimeSpan]::FromSeconds($TimeoutSeconds))) {
            $result = $ps.EndInvoke($handle)
            return [bool]$result[0]
        } else {
            $ps.Stop()
            try { $ps.EndInvoke($handle) } catch { }
            return $false
        }
    } catch {
        return $false
    } finally {
        if ($ps) { $ps.Dispose() }
    }
}

# ─────────────────────────────────────────────────────────────────────────────
# Helper: Check if a DFS folder link exists
# ─────────────────────────────────────────────────────────────────────────────

function Test-DfsFolderExists {
    param(
        [Parameter(Mandatory=$true)]
        [string] $FolderPath
    )
    try {
        $folder = Get-DfsnFolder -Path $FolderPath -ErrorAction Stop
        return ($null -ne $folder)
    } catch {
        return $false
    }
}

# ─────────────────────────────────────────────────────────────────────────────
# Progress / checkpoint helpers
# ─────────────────────────────────────────────────────────────────────────────

# Progress is stored as JSON: { "completedRows": { "LinkPath|TargetPath": "timestamp", ... } }

function Read-ProgressFile {
    param([string] $Path)
    if (-not (Test-Path $Path)) { return @{} }
    try {
        $json = Get-Content -Path $Path -Raw | ConvertFrom-Json
        $ht = @{}
        if ($json.completedRows) {
            $json.completedRows.PSObject.Properties | ForEach-Object { $ht[$_.Name] = $_.Value }
        }
        return $ht
    } catch {
        Write-Warning "Could not parse progress file '$Path': $($_.Exception.Message). Starting fresh."
        return @{}
    }
}

function Save-ProgressFile {
    param(
        [string]    $Path,
        [hashtable] $CompletedRows
    )
    $obj = [pscustomobject]@{ completedRows = $CompletedRows }
    $obj | ConvertTo-Json -Depth 3 | Set-Content -Path $Path -Force -WhatIf:$false
}

function Get-ProgressKey {
    param([string] $LinkPath, [string] $TargetPath)
    return "${LinkPath}|${TargetPath}"
}

# Resolve progress file path
if ([string]::IsNullOrWhiteSpace($ProgressFile)) {
    $csvBaseName = [System.IO.Path]::GetFileNameWithoutExtension($RemovalsCsvPath)
    $ProgressFile = Join-Path $PSScriptRoot "logs\repair_progress_$csvBaseName.json"
}

if ($ResetProgress -and (Test-Path $ProgressFile)) {
    Remove-Item -Path $ProgressFile -Force -WhatIf:$false
    Write-Host "Progress file reset: $ProgressFile" -ForegroundColor Yellow
}

$completedRows = Read-ProgressFile -Path $ProgressFile
if ($completedRows.Count -gt 0) {
    Write-Host "Resuming with $($completedRows.Count) previously completed row(s) from: $ProgressFile" -ForegroundColor Cyan
} else {
    Write-Host "Progress file: $ProgressFile" -ForegroundColor Gray
}

try {

# ─────────────────────────────────────────────────────────────────────────────
# Ensure DFSN module is available
# ─────────────────────────────────────────────────────────────────────────────

Write-Status "Importing DFSN module..."
try {
    Import-Module DFSN -ErrorAction Stop
    Write-Status "DFSN module loaded."
} catch {
    Write-Error "The DFSN PowerShell module is required but could not be loaded. Ensure the DFS Namespaces feature and its PowerShell cmdlets are installed.`n$($_.ScriptStackTrace)"
    return
}

# ─────────────────────────────────────────────────────────────────────────────
# Read and validate the removals CSV
# ─────────────────────────────────────────────────────────────────────────────

if (-not (Test-Path $RemovalsCsvPath)) {
    Write-Error "Removals CSV not found: $RemovalsCsvPath"
    return
}

Write-Status "Reading CSV: $RemovalsCsvPath"
$allRows = Import-Csv -Path $RemovalsCsvPath
$totalCsvRows = $allRows.Count
Write-Status "Loaded $totalCsvRows row(s) from CSV."

# Validate expected columns
$expectedColumns = @("Timestamp", "DfsServer", "LinkPath", "TargetPath", "Reason", "Status")
$actualColumns = $allRows[0].PSObject.Properties.Name
$missingColumns = $expectedColumns | Where-Object { $_ -notin $actualColumns }
if ($missingColumns.Count -gt 0) {
    Write-Error "CSV is missing expected columns: $($missingColumns -join ', '). Expected: $($expectedColumns -join ', ')"
    return
}

# Filter to only rows that were actually removed
$removedRows = @($allRows | Where-Object { $_.Status -eq "Removed" })
$totalRemoved = $removedRows.Count
$totalSkipped = $totalCsvRows - $totalRemoved
Write-Host "  Rows with Status='Removed': $totalRemoved (skipping $totalSkipped non-Removed rows)" -ForegroundColor Green

# repairOutcomes is declared above as ConcurrentDictionary

# Updated removals CSV path (written in finally block so it survives early termination).
$updatedCsvPath = [System.IO.Path]::ChangeExtension($RemovalsCsvPath, $null).TrimEnd('.') + "_updated.csv"

if ($totalRemoved -eq 0) {
    Write-Host "No targets to recover. Exiting." -ForegroundColor Yellow
    return
}

# ─────────────────────────────────────────────────────────────────────────────
# Process removed targets in parallel
# ─────────────────────────────────────────────────────────────────────────────

Write-Host ""
Write-Host "═══════════════════════════════════════════════════════════════" -ForegroundColor Cyan
Write-Host " Checking reachability and restoring targets (parallel x$ThrottleLimit)" -ForegroundColor Cyan
Write-Host "═══════════════════════════════════════════════════════════════" -ForegroundColor Cyan

$phaseStartTime = Get-Date
Write-Status "Starting parallel reachability checks and restoration ($totalRemoved targets, throttle=$ThrottleLimit)..."

# Capture WhatIf preference for use inside parallel blocks (ShouldProcess is unavailable there)
$isWhatIf = $WhatIfPreference

# Pre-filter rows that were already completed in a previous run, count them, and process the rest
$rowsToProcess = @()
$totalSkippedResume = 0
foreach ($row in $removedRows) {
    $progressKey = "$($row.LinkPath)|$($row.TargetPath)"
    if ($completedRows.ContainsKey($progressKey)) {
        $totalSkippedResume++
    } else {
        $rowsToProcess += $row
    }
}

if ($totalSkippedResume -gt 0) {
    Write-Host "  Skipping $totalSkippedResume already-completed row(s) from previous run." -ForegroundColor Cyan
}

$rowsToProcessCount = $rowsToProcess.Count
Write-Status "Processing $rowsToProcessCount target(s) in parallel..."

# ── Background progress monitor ──
# Polls sharedCounters every 2 seconds, writes Write-Progress updates, and
# periodically flushes the progress file so that completed rows survive
# an interrupted run.
$progressJob = Start-ThreadJob -ScriptBlock {
    param($counters, $total, $startTime, $newCompleted, $existingCompleted, $progressFilePath)
    $lastFlushCount = 0
    while ($true) {
        Start-Sleep -Seconds 2
        $done = $counters['Processed']
        if ($total -gt 0) {
            $pct = [math]::Min([math]::Round(($done / $total) * 100, 1), 100)
            $elapsed = (Get-Date) - $startTime
            $reachable   = $counters['Reachable']
            $unreachable = $counters['Unreachable']
            $restored    = $counters['Restored']
            $errors      = $counters['Errors']
            $status = "$done / $total ($pct%) | Reachable: $reachable | Unreachable: $unreachable | Restored: $restored | Errors: $errors | Elapsed: $($elapsed.ToString('mm\:ss'))"
            Write-Progress -Activity "Repair-DfsTargetsFromCsv" -Status $status -PercentComplete $pct
        }
        # Flush progress file every 30 new completions
        $currentCount = $newCompleted.Count
        if (($currentCount - $lastFlushCount) -ge 30) {
            try {
                $merged = $existingCompleted.Clone()
                foreach ($kvp in $newCompleted.GetEnumerator()) { $merged[$kvp.Key] = $kvp.Value }
                $obj = [pscustomobject]@{ completedRows = $merged }
                $obj | ConvertTo-Json -Depth 3 | Set-Content -Path $progressFilePath -Force
                $lastFlushCount = $currentCount
            } catch {
                # Non-fatal — final save after the loop will catch up
            }
        }
        if ($done -ge $total) { break }
    }
    Write-Progress -Activity "Repair-DfsTargetsFromCsv" -Completed
} -ArgumentList $sharedCounters, $rowsToProcessCount, $phaseStartTime, $newCompletedRows, $completedRows, $ProgressFile

$rowsToProcess | ForEach-Object -ThrottleLimit $ThrottleLimit -Parallel {
    $row = $_
    $linkPath   = $row.LinkPath
    $targetPath = $row.TargetPath
    $dfsServer  = $row.DfsServer
    $outcomeKey = "$linkPath|$targetPath"

    # Import references from parent scope
    $counters        = $using:sharedCounters
    $outcomes        = $using:repairOutcomes
    $newCompleted    = $using:newCompletedRows
    $recoveryBag     = $using:recoveryRecords
    $timeoutSec      = $using:ReachabilityTimeoutSeconds
    $whatIf          = $using:isWhatIf
    $total           = $using:rowsToProcessCount

    # ── Reachability check (inline Test-TargetReachable) ──
    $reachable = $false
    $ps = $null
    try {
        $ps = [PowerShell]::Create()
        $ps.AddCommand("Test-Path").AddParameter("Path", $targetPath) | Out-Null
        $handle = $ps.BeginInvoke()
        if ($handle.AsyncWaitHandle.WaitOne([TimeSpan]::FromSeconds($timeoutSec))) {
            $result = $ps.EndInvoke($handle)
            $reachable = [bool]$result[0]
        } else {
            $ps.Stop()
        }
    } catch {
        # reachable stays $false
    } finally {
        if ($ps) { $ps.Dispose() }
    }

    $counters['Processed']++

    if (-not $reachable) {
        $counters['Unreachable']++
        $outcomes.TryAdd($outcomeKey, "Unreachable") | Out-Null
        $newCompleted.TryAdd($outcomeKey, (Get-Date).ToString("o")) | Out-Null
        $done = $counters['Processed']
        Write-Host "  [$done/$total] UNREACHABLE: $targetPath" -ForegroundColor DarkGray
        return  # next parallel item
    }

    $counters['Reachable']++
    $done = $counters['Processed']
    Write-Host "  [$done/$total] REACHABLE: $targetPath  (Link: $linkPath)" -ForegroundColor Yellow

    # ── DFS link check (inline Test-DfsFolderExists) ──
    Import-Module DFSN -ErrorAction SilentlyContinue
    $linkExists = $false
    try {
        $folder = Get-DfsnFolder -Path $linkPath -ErrorAction Stop
        $linkExists = ($null -ne $folder)
    } catch {
        $linkExists = $false
    }

    if ($linkExists) {
        if ($whatIf) {
            $counters['Restored']++
            $outcomes.TryAdd($outcomeKey, "WouldRestore") | Out-Null
            $recoveryBag.Add([PSCustomObject]@{
                Timestamp  = (Get-Date).ToString("o")
                DfsServer  = $dfsServer
                LinkPath   = $linkPath
                TargetPath = $targetPath
                Action     = "TargetReAdded"
                Status     = "WhatIf"
            })
            Write-Host "    [WhatIf] Would re-add target to existing link: $linkPath -> $targetPath" -ForegroundColor Cyan
        } else {
            try {
                New-DfsnFolderTarget -Path $linkPath -TargetPath $targetPath -ErrorAction Stop
                $counters['TargetsReadded']++
                $counters['Restored']++
                $outcomes.TryAdd($outcomeKey, "Restored") | Out-Null
                $recoveryBag.Add([PSCustomObject]@{
                    Timestamp  = (Get-Date).ToString("o")
                    DfsServer  = $dfsServer
                    LinkPath   = $linkPath
                    TargetPath = $targetPath
                    Action     = "TargetReAdded"
                    Status     = "Restored"
                })
                Write-Host "    RESTORED (target re-added): $linkPath -> $targetPath" -ForegroundColor Green
            } catch {
                $outcomes.TryAdd($outcomeKey, "RepairFailed") | Out-Null
                $recoveryBag.Add([PSCustomObject]@{
                    Timestamp  = (Get-Date).ToString("o")
                    DfsServer  = $dfsServer
                    LinkPath   = $linkPath
                    TargetPath = $targetPath
                    Action     = "TargetReAdded"
                    Status     = "Failed: $($_.Exception.Message)"
                })
                $counters['Errors']++
                Write-Warning "    FAILED to re-add target '$targetPath' to '$linkPath': $($_.Exception.Message)"
            }
        }
    } else {
        if ($whatIf) {
            $counters['Restored']++
            $outcomes.TryAdd($outcomeKey, "WouldRestore") | Out-Null
            $recoveryBag.Add([PSCustomObject]@{
                Timestamp  = (Get-Date).ToString("o")
                DfsServer  = $dfsServer
                LinkPath   = $linkPath
                TargetPath = $targetPath
                Action     = "LinkRecreated"
                Status     = "WhatIf"
            })
            Write-Host "    [WhatIf] Would recreate link with target: $linkPath -> $targetPath" -ForegroundColor Cyan
        } else {
            try {
                New-DfsnFolder -Path $linkPath -TargetPath $targetPath -ErrorAction Stop
                $counters['LinksRecreated']++
                $counters['Restored']++
                $outcomes.TryAdd($outcomeKey, "Restored") | Out-Null
                $recoveryBag.Add([PSCustomObject]@{
                    Timestamp  = (Get-Date).ToString("o")
                    DfsServer  = $dfsServer
                    LinkPath   = $linkPath
                    TargetPath = $targetPath
                    Action     = "LinkRecreated"
                    Status     = "Restored"
                })
                Write-Host "    RESTORED (link recreated): $linkPath -> $targetPath" -ForegroundColor Green
            } catch {
                $outcomes.TryAdd($outcomeKey, "RepairFailed") | Out-Null
                $recoveryBag.Add([PSCustomObject]@{
                    Timestamp  = (Get-Date).ToString("o")
                    DfsServer  = $dfsServer
                    LinkPath   = $linkPath
                    TargetPath = $targetPath
                    Action     = "LinkRecreated"
                    Status     = "Failed: $($_.Exception.Message)"
                })
                $counters['Errors']++
                Write-Warning "    FAILED to recreate link '$linkPath' with target '$targetPath': $($_.Exception.Message)"
            }
        }
    }

    # Mark row as completed
    $newCompleted.TryAdd($outcomeKey, (Get-Date).ToString("o")) | Out-Null
}

$totalElapsed = (Get-Date) - $phaseStartTime

# Stop the progress monitor job
$progressJob | Wait-Job -Timeout 5 | Out-Null
$progressJob | Remove-Job -Force -ErrorAction SilentlyContinue
Write-Progress -Activity "Repair-DfsTargetsFromCsv" -Completed

Write-Status "Parallel processing complete. Total processing time: $($totalElapsed.ToString('mm\:ss\.fff'))"

# ─────────────────────────────────────────────────────────────────────────────
# Batch-write progress file with all newly completed rows
# ─────────────────────────────────────────────────────────────────────────────

Write-Status "Saving progress file with $($newCompletedRows.Count) newly completed row(s)..."
foreach ($kvp in $newCompletedRows.GetEnumerator()) {
    $completedRows[$kvp.Key] = $kvp.Value
}
Save-ProgressFile -Path $ProgressFile -CompletedRows $completedRows
Write-Status "Progress file saved."

# ─────────────────────────────────────────────────────────────────────────────
# Batch-write recovery report CSV
# ─────────────────────────────────────────────────────────────────────────────

$recoveryItems = @($recoveryRecords.ToArray())
if ($recoveryItems.Count -gt 0) {
    $recoveryItems | Export-Csv -Path $recoveryReportPath -NoTypeInformation -Force -WhatIf:$false
    Write-Status "Recovery report written ($($recoveryItems.Count) entries)."
}

# ─────────────────────────────────────────────────────────────────────────────
# Write updated removals CSV
# ─────────────────────────────────────────────────────────────────────────────
# Produces a copy of the original removals CSV with the Status column updated
# to reflect repair outcomes:
#   Restored     — target was successfully re-added
#   WouldRestore — target is reachable and would be restored (-WhatIf)
#   Unreachable  — target was confirmed unreachable, removal was correct
#   RepairFailed — target is reachable but repair failed
#   (unchanged)  — rows that were not Status="Removed" pass through as-is

$updatedCsvPath = [System.IO.Path]::ChangeExtension($RemovalsCsvPath, $null).TrimEnd('.') + "_updated.csv"
Write-Status "Writing updated removals CSV: $updatedCsvPath"

$updatedRows = foreach ($r in $allRows) {
    $key = "$($r.LinkPath)|$($r.TargetPath)"
    $outcomeValue = $null
    if ($r.Status -eq "Removed" -and $repairOutcomes.TryGetValue($key, [ref]$outcomeValue)) {
        # Clone the row and update status
        $props = [ordered]@{}
        foreach ($p in $r.PSObject.Properties) {
            $props[$p.Name] = $p.Value
        }
        $props["Status"] = $outcomeValue
        [PSCustomObject]$props
    } else {
        $r
    }
}
$updatedRows | Export-Csv -Path $updatedCsvPath -NoTypeInformation -Force -WhatIf:$false
Write-Status "Updated removals CSV written ($($updatedRows.Count) rows)."

# ─────────────────────────────────────────────────────────────────────────────
# Recovery report
# ─────────────────────────────────────────────────────────────────────────────

if ($recoveryItems.Count -gt 0) {
    Write-Host ""
    Write-Host "  Recovery report:      $recoveryReportPath ($($recoveryItems.Count) entries)" -ForegroundColor Cyan
} else {
    Write-Host "  Recovery report:      (none — no targets were restored)" -ForegroundColor Gray
}

# ─────────────────────────────────────────────────────────────────────────────
# Summary (read from thread-safe counters)
# ─────────────────────────────────────────────────────────────────────────────

$totalReachable      = $sharedCounters['Reachable']
$totalUnreachable    = $sharedCounters['Unreachable']
$totalRestored       = $sharedCounters['Restored']
$totalLinksRecreated = $sharedCounters['LinksRecreated']
$totalTargetsReadded = $sharedCounters['TargetsReadded']
$totalErrors         = $sharedCounters['Errors']

Write-Host ""
Write-Host "═══════════════════════════════════════════════════════════════" -ForegroundColor Cyan
Write-Host " Summary" -ForegroundColor Cyan
Write-Host "═══════════════════════════════════════════════════════════════" -ForegroundColor Cyan
Write-Host "  CSV rows loaded:      $totalCsvRows" -ForegroundColor Green
Write-Host "  Rows (Removed):       $totalRemoved" -ForegroundColor Green
Write-Host "  Rows skipped (other): $totalSkipped" -ForegroundColor Green
Write-Host "  Rows skipped (resume):$totalSkippedResume" -ForegroundColor Green
Write-Host "  Targets reachable:    $totalReachable" -ForegroundColor Green
Write-Host "  Targets unreachable:  $totalUnreachable" -ForegroundColor Green

if ($WhatIfPreference) {
    Write-Host "  Targets to restore:   $totalRestored" -ForegroundColor Yellow
} else {
    Write-Host "  Targets restored:     $totalRestored" -ForegroundColor Yellow
}

Write-Host "    Links recreated:    $totalLinksRecreated" -ForegroundColor Yellow
Write-Host "    Targets re-added:   $totalTargetsReadded" -ForegroundColor Yellow
Write-Host "  Errors:               $totalErrors" -ForegroundColor $(if ($totalErrors -gt 0) { "Red" } else { "Green" })
Write-Host "  Throttle limit:       $ThrottleLimit" -ForegroundColor Gray
Write-Host "  Progress file:        $ProgressFile" -ForegroundColor Gray
Write-Host "  Updated removals CSV: $updatedCsvPath" -ForegroundColor Cyan
Write-Host ""

} finally {

    if ($TranscriptStarted) {
        Stop-Transcript -WhatIf:$false | Out-Null
    }
}
